# Четем входното число n от конзолата
n = int(input())

# Брояч на валидните комбинации
counter = 0

# Използваме три вложени цикъла, които генерират всички комбинации от 0 до n
for x1 in range(n + 1):  # x1 може да бъде от 0 до n включително
    for x2 in range(n + 1):  # x2 може да бъде от 0 до n включително
        for x3 in range(n + 1):  # x3 може да бъде от 0 до n включително
            if x1 + x2 + x3 == n:  # Проверяваме дали сборът е равен на n
                counter += 1  # Увеличаваме броя на валидните комбинации

# Отпечатваме крайния брой на валидните комбинации
print(counter)
