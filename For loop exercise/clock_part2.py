# Външен цикъл за часовете (от 0 до 23 включително)
for hour in range(24):
    # Среден цикъл за минутите (от 0 до 59 включително)
    for minute in range(60):
        # Вътрешен цикъл за секундите (от 0 до 59 включително)
        for second in range(60):
            # Принтиране на текущия час, минути и секунди във формат "{час} : {минути} : {секунди}"
            print(f"{hour} : {minute} : {second}")
