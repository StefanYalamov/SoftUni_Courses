# Безкраен цикъл за четене на числата
while True:
    number = float(input())  # Четем входно число от потребителя

    # Проверка дали числото е отрицателно
    if number < 0:
        print("Negative number!")  # Отпечатваме съобщение за отрицателно число
        break  # Прекъсваме изпълнението на цикъла

    # Ако числото е положително, умножаваме го по 2 и отпечатваме резултата
    result = number * 2
    print(f"Result: {result:.2f}")  # Форматираме резултата до втория знак
