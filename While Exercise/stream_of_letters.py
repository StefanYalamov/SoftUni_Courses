# Вход: Поредица от символи, докато не получим "End"
current_word = ""  # Запазва текущата дума
has_c = False  # Проверка дали "c" е срещната
has_o = False  # Проверка дали "o" е срещната
has_n = False  # Проверка дали "n" е срещната

# Четене на символи от конзолата
while True:
    char = input()

    # Ако въведем "End", излизаме от цикъла
    if char == "End":
        break

    # Проверка дали символът е латинска буква
    if char.isalpha():
        # Проверка за срещане на специалните букви
        if char == "c":
            if has_c:
                current_word += char  # Добавяме "c", ако вече е била срещната преди
            has_c = True  # Отбелязваме "c" като срещната
        elif char == "o":
            if has_o:
                current_word += char  # Добавяме "o", ако вече е била срещната преди
            has_o = True  # Отбелязваме "o" като срещната
        elif char == "n":
            if has_n:
                current_word += char  # Добавяме "n", ако вече е била срещната преди
            has_n = True  # Отбелязваме "n" като срещната
        else:
            # Ако символът е друга буква, го добавяме директно към думата
            current_word += char

        # Проверка дали сме срещнали и трите букви
        if has_c and has_o and has_n:
            # Отпечатваме думата, ако имаме всичките три букви
            print(current_word, end=" ")  # Използваме end=" " за добавяне на интервал
            # Рестартираме състоянието за нова дума
            current_word = ""
            has_c = False
            has_o = False
            has_n = False
