# Обхождаме всички числа от 1 до 100 включително
for number in range(1, 101):
    # Проверяваме дали числото се дели на 3 без остатък
    if number % 3 == 0:
        print(number)  # Ако е вярно, отпечатваме числото


# Допълнително решение
number = 3
while number <= 100:
    print(number)
    number += 3  # Увеличаваме числото с 3
